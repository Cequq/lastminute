-- Улаанбаатарын цагаар "өнөөдрөөс N хоногийн дараах HH:MM". Өнгөрсөн бол маргааш.
create or replace function pg_temp.at_local(p_days int, p_time time)
returns timestamptz language sql as $$
  select case when t < now() + interval '20 minutes' then t + interval '1 day' else t end
  from (select ((((now() at time zone 'Asia/Ulaanbaatar')::date + p_days) + p_time)
                at time zone 'Asia/Ulaanbaatar') as t) x;
$$;

